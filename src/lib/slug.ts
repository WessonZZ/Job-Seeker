/**
 * 生成 ASCII-only URL slug
 * 优先使用已知映射，否则进行简化罗马化
 */
export function generateSlug(name: string): string {
  const trimmed = name.trim();

  // 1. 优先使用已知映射
  if (KNOWN_SLUGS[trimmed]) {
    return KNOWN_SLUGS[trimmed];
  }

  // 2. 对已知映射做模糊匹配
  const keys = Object.keys(KNOWN_SLUGS).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (trimmed.includes(key) || key.includes(trimmed)) {
      return KNOWN_SLUGS[key];
    }
  }

  // 3. 提取英文字母和数字
  const asciiPart = trimmed.replace(/[^a-zA-Z0-9\s.-]/g, " ").trim();
  if (asciiPart.length >= 2) {
    return asciiPart
      .toLowerCase()
      .replace(/\s+/g, "-")
      .replace(/[^a-z0-9-]/g, "")
      .slice(0, 60);
  }

  // 4. 纯中文名 → 取前两个字的拼音首字母
  const pinyinInitials = trimmed
    .split("")
    .filter((ch) => /[一-鿿]/.test(ch))
    .slice(0, 4)
    .map((ch) => ch2init(ch))
    .join("");

  if (pinyinInitials) {
    return pinyinInitials.toLowerCase().slice(0, 60);
  }

  // 5. 最后的回退：用 random 后缀
  return `company-${Math.random().toString(36).slice(2, 8)}`;
}

